// Package generator generates fluent Go client code from protobuf services
// annotated with the options in proto/fluent/v1/options.proto.
//
// The generated code depends on the fluent runtime package and on a type named
// Client in the output package that embeds *fluent.Conn. With Config.Client set,
// that type (plus Dial, New and With) is generated too.
package generator

import (
	"fmt"
	"regexp"
	"strings"
	"unicode"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"

	"github.com/wakelesstuna/protoc-gen-go-fluent/fluentpb"
)

const (
	contextPkg = protogen.GoImportPath("context")
	iterPkg    = protogen.GoImportPath("iter")
	grpcPkg    = protogen.GoImportPath("google.golang.org/grpc")
	fluentPkg  = protogen.GoImportPath("github.com/wakelesstuna/protoc-gen-go-fluent/fluent")
)

// Paging field names required on every list RPC (AIP-158).
const (
	pageSizeField      = "page_size"
	pageTokenField     = "page_token"
	nextPageTokenField = "next_page_token"
)

var (
	// Methods and fields on Client that come from fluent.Conn or the generated client.
	reservedClientMethods = map[string]bool{"Close": true, "With": true, "ClientConn": true, "Outgoing": true, "Conn": true}
	// Methods every generated query has.
	reservedQueryMethods = map[string]bool{"PageSize": true, "Limit": true, "Page": true, "All": true, "Collect": true}
	// Struct fields every generated query has.
	reservedQueryFields = map[string]bool{"c": true, "paging": true}

	exportedIdent = regexp.MustCompile(`^[A-Z][A-Za-z0-9_]*$`)
)

// Config controls the generated file.
type Config struct {
	PackageName string
	ImportPath  protogen.GoImportPath
	Filename    string
	// Client generates the Client type with Dial, New and With. When false, the
	// output package must declare `type Client struct { *fluent.Conn; ... }` itself.
	Client bool
}

type resource struct {
	name    string
	parent  *resource
	idField string
	chain   []*resource // root first, ending with this resource
}

type setter struct {
	field    *protogen.Field
	name     string
	shortcut string
}

type listQuery struct {
	method     *protogen.Method
	service    *protogen.Service
	importPath protogen.GoImportPath // of the service's generated gRPC code
	parent     *resource
	name       string
	ids        []*protogen.Field
	pageSize   *protogen.Field
	pageToken  *protogen.Field
	nextToken  *protogen.Field
	items      *protogen.Field
	setters    []setter
}

// Generate writes cfg.Filename for every annotated file in p. It writes nothing
// when no resources or list methods are declared.
func Generate(p *protogen.Plugin, cfg Config) error {
	resources, byName, err := collectResources(p)
	if err != nil {
		return err
	}
	lists, err := collectLists(p, byName)
	if err != nil {
		return err
	}
	if err := checkNames(resources, lists); err != nil {
		return err
	}
	if len(resources) == 0 && len(lists) == 0 {
		return nil
	}

	g := p.NewGeneratedFile(cfg.Filename, cfg.ImportPath)
	g.P("// Code generated by protoc-gen-go-fluent. DO NOT EDIT.")
	g.P()
	g.P("package ", cfg.PackageName)
	g.P()
	if cfg.Client {
		genClient(g)
	}
	for _, r := range resources {
		genResource(g, r)
	}
	for _, q := range lists {
		genList(g, q)
	}
	return nil
}

func collectResources(p *protogen.Plugin) ([]*resource, map[string]*resource, error) {
	byName := map[string]*resource{}
	parentOf := map[*resource]string{}
	var order []*resource

	for _, f := range p.Files {
		if !f.Generate {
			continue
		}
		decls, _ := proto.GetExtension(f.Desc.Options(), fluentpb.E_Resource).([]*fluentpb.Resource)
		for _, d := range decls {
			if !exportedIdent.MatchString(d.GetName()) {
				return nil, nil, fmt.Errorf("%s: resource name %q must be an exported Go identifier", f.Desc.Path(), d.GetName())
			}
			if d.GetIdField() == "" {
				return nil, nil, fmt.Errorf("%s: resource %s needs id_field", f.Desc.Path(), d.GetName())
			}
			if _, dup := byName[d.GetName()]; dup {
				return nil, nil, fmt.Errorf("%s: resource %s declared twice", f.Desc.Path(), d.GetName())
			}
			r := &resource{name: d.GetName(), idField: d.GetIdField()}
			byName[r.name] = r
			parentOf[r] = d.GetParent()
			order = append(order, r)
		}
	}

	for _, r := range order {
		if pn := parentOf[r]; pn != "" {
			if r.parent = byName[pn]; r.parent == nil {
				return nil, nil, fmt.Errorf("resource %s: unknown parent %q", r.name, pn)
			}
		}
	}
	for _, r := range order {
		seen := map[*resource]bool{}
		ids := map[string]bool{}
		for x := r; x != nil; x = x.parent {
			if seen[x] {
				return nil, nil, fmt.Errorf("resource %s: parent cycle", r.name)
			}
			if ids[x.idField] {
				return nil, nil, fmt.Errorf("resource %s: id_field %q repeats an ancestor's", r.name, x.idField)
			}
			seen[x], ids[x.idField] = true, true
			r.chain = append([]*resource{x}, r.chain...)
		}
	}
	return order, byName, nil
}

func collectLists(p *protogen.Plugin, resources map[string]*resource) ([]*listQuery, error) {
	var lists []*listQuery
	for _, f := range p.Files {
		if !f.Generate {
			continue
		}
		for _, s := range f.Services {
			for _, m := range s.Methods {
				if !proto.HasExtension(m.Desc.Options(), fluentpb.E_List) {
					continue
				}
				q, err := newListQuery(m, resources)
				if err != nil {
					return nil, fmt.Errorf("%s: %w", m.Desc.FullName(), err)
				}
				q.service, q.importPath = s, f.GoImportPath
				lists = append(lists, q)
			}
		}
	}
	return lists, nil
}

func newListQuery(m *protogen.Method, resources map[string]*resource) (*listQuery, error) {
	if m.Desc.IsStreamingClient() || m.Desc.IsStreamingServer() {
		return nil, fmt.Errorf("streaming methods are not supported")
	}
	opt, _ := proto.GetExtension(m.Desc.Options(), fluentpb.E_List).(*fluentpb.ListMethod)

	q := &listQuery{method: m, name: opt.GetName()}
	for _, f := range m.Output.Fields {
		if f.Desc.IsList() && f.Message != nil {
			if q.items != nil {
				return nil, fmt.Errorf("response %s has more than one repeated message field", m.Output.Desc.Name())
			}
			q.items = f
		}
	}
	if q.items == nil {
		return nil, fmt.Errorf("response %s has no repeated message field to list", m.Output.Desc.Name())
	}

	if q.name == "" {
		// ListBooks -> Books. An RPC named just "List" falls back to the items field: books -> Books.
		if q.name = strings.TrimPrefix(m.GoName, "List"); q.name == "" {
			q.name = q.items.GoName
		}
	}
	if !exportedIdent.MatchString(q.name) {
		return nil, fmt.Errorf("query name %q must be an exported Go identifier; set it with option (fluent.v1.list) = {name: \"...\"}", q.name)
	}
	if pn := opt.GetParent(); pn != "" {
		if q.parent = resources[pn]; q.parent == nil {
			return nil, fmt.Errorf("unknown parent resource %q", pn)
		}
	}

	var err error
	if q.pageSize, err = singular(m.Input, pageSizeField, protoreflect.Int32Kind); err != nil {
		return nil, err
	}
	if q.pageToken, err = singular(m.Input, pageTokenField, protoreflect.StringKind); err != nil {
		return nil, err
	}
	if q.nextToken, err = singular(m.Output, nextPageTokenField, protoreflect.StringKind); err != nil {
		return nil, err
	}

	handled := map[string]bool{pageSizeField: true, pageTokenField: true}
	if q.parent != nil {
		for _, r := range q.parent.chain {
			id, err := singular(m.Input, r.idField, protoreflect.StringKind)
			if err != nil {
				return nil, fmt.Errorf("%w (id_field of resource %s)", err, r.name)
			}
			q.ids = append(q.ids, id)
			handled[r.idField] = true
		}
	}

	for _, f := range m.Input.Fields {
		if handled[string(f.Desc.Name())] {
			continue
		}
		fopt, _ := proto.GetExtension(f.Desc.Options(), fluentpb.E_Field).(*fluentpb.Field)
		if fopt.GetSkip() {
			continue
		}
		if err := checkSetterType(f); err != nil {
			return nil, err
		}
		s := setter{field: f, name: fopt.GetSetter(), shortcut: fopt.GetEnumShortcut()}
		if s.name == "" {
			s.name = f.GoName
		}
		if s.shortcut != "" {
			if f.Enum == nil {
				return nil, fmt.Errorf("field %s: enum_shortcut needs an enum field", f.Desc.Name())
			}
			if strings.Count(s.shortcut, "%s") != 1 || strings.Count(s.shortcut, "%") != 1 {
				return nil, fmt.Errorf("field %s: enum_shortcut %q must contain exactly one %%s", f.Desc.Name(), s.shortcut)
			}
		}
		q.setters = append(q.setters, s)
	}

	return q, nil
}

func singular(msg *protogen.Message, name string, kind protoreflect.Kind) (*protogen.Field, error) {
	for _, f := range msg.Fields {
		if string(f.Desc.Name()) != name {
			continue
		}
		if f.Desc.Kind() != kind || f.Desc.Cardinality() == protoreflect.Repeated || f.Desc.HasPresence() {
			return nil, fmt.Errorf("%s.%s must be a plain singular %s", msg.Desc.Name(), name, kind)
		}
		return f, nil
	}
	return nil, fmt.Errorf("%s is missing field %s", msg.Desc.Name(), name)
}

func checkSetterType(f *protogen.Field) error {
	switch {
	case f.Desc.IsList() || f.Desc.IsMap():
		return fmt.Errorf("field %s: repeated and map fields are not supported; mark it (fluent.v1.field).skip", f.Desc.Name())
	case f.Desc.HasPresence():
		return fmt.Errorf("field %s: optional and oneof fields are not supported; mark it (fluent.v1.field).skip", f.Desc.Name())
	case f.Desc.Kind() == protoreflect.MessageKind || f.Desc.Kind() == protoreflect.GroupKind:
		return fmt.Errorf("field %s: message fields are not supported; mark it (fluent.v1.field).skip", f.Desc.Name())
	}
	return nil
}

// checkNames rejects generated identifiers that would collide.
func checkNames(resources []*resource, lists []*listQuery) error {
	methods := map[string]string{} // "<receiver>.<method>" -> what declared it
	declare := func(recv, name, what string) error {
		key := recv + "." + name
		if prev, dup := methods[key]; dup {
			return fmt.Errorf("%s and %s both generate %s", prev, what, key)
		}
		methods[key] = what
		return nil
	}
	recvOf := func(r *resource) string {
		if r == nil {
			return "Client"
		}
		return r.name + "Ref"
	}
	types := map[string]bool{"Client": true}

	for _, r := range resources {
		if r.parent == nil && reservedClientMethods[r.name] {
			return fmt.Errorf("resource %s collides with Client.%s", r.name, r.name)
		}
		if types[r.name+"Ref"] {
			return fmt.Errorf("type %sRef generated twice", r.name)
		}
		types[r.name+"Ref"] = true
		if err := declare(recvOf(r.parent), r.name, "resource "+r.name); err != nil {
			return err
		}
	}
	for _, q := range lists {
		what := string(q.method.Desc.FullName())
		if q.parent == nil && reservedClientMethods[q.name] {
			return fmt.Errorf("%s collides with Client.%s", what, q.name)
		}
		if types[q.name+"Query"] {
			return fmt.Errorf("%s: type %sQuery generated twice", what, q.name)
		}
		types[q.name+"Query"] = true
		if err := declare(recvOf(q.parent), q.name, what); err != nil {
			return err
		}

		fields := map[string]bool{}
		for _, id := range q.ids {
			fields[lowerFirst(id.GoName)] = true
		}
		for _, s := range q.setters {
			fv := lowerFirst(s.field.GoName)
			if reservedQueryFields[fv] || fields[fv] {
				return fmt.Errorf("%s: field %s collides with a generated struct field", what, s.field.Desc.Name())
			}
			fields[fv] = true

			names := []string{s.name}
			if s.shortcut != "" {
				for _, v := range s.field.Enum.Values {
					if v.Desc.Number() != 0 {
						names = append(names, shortcutName(s, v))
					}
				}
			}
			for _, n := range names {
				if !exportedIdent.MatchString(n) {
					return fmt.Errorf("%s: setter %q must be an exported Go identifier", what, n)
				}
				if reservedQueryMethods[n] {
					return fmt.Errorf("%s: setter %s collides with %sQuery.%s", what, n, q.name, n)
				}
				if err := declare(q.name+"Query", n, what+"."+string(s.field.Desc.Name())); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

func genClient(g *protogen.GeneratedFile) {
	conn := g.QualifiedGoIdent(fluentPkg.Ident("Conn"))
	g.P("// Client calls the API. It is safe for concurrent use: create one per process")
	g.P("// and derive per-request variants with With.")
	g.P("type Client struct {")
	g.P("*", conn)
	g.P("}")
	g.P()
	g.P("// Dial connects to target. Pass transport credentials in opts, e.g.")
	g.P("// grpc.WithTransportCredentials(credentials.NewTLS(nil)). Close the Client when done.")
	g.P("func Dial(target string, opts ...", grpcPkg.Ident("DialOption"), ") (*Client, error) {")
	g.P("conn, err := ", fluentPkg.Ident("Dial"), "(target, opts...)")
	g.P("if err != nil {")
	g.P("return nil, err")
	g.P("}")
	g.P("return &Client{Conn: conn}, nil")
	g.P("}")
	g.P()
	g.P("// New creates a Client on an existing connection. The caller keeps ownership of cc.")
	g.P("func New(cc ", grpcPkg.Ident("ClientConnInterface"), ") *Client {")
	g.P("return &Client{Conn: ", fluentPkg.Ident("NewConn"), "(cc)}")
	g.P("}")
	g.P()
	g.P("// With returns a Client sharing c's connection that applies fns to every call's")
	g.P("// context, e.g. fluent.Metadata(\"authorization\", \"Bearer \"+token).")
	g.P("func (c *Client) With(fns ...", fluentPkg.Ident("ContextFunc"), ") *Client {")
	g.P("return &Client{Conn: c.Conn.With(fns...)}")
	g.P("}")
	g.P()
}

func genResource(g *protogen.GeneratedFile, r *resource) {
	ref := r.name + "Ref"
	param := idVar(r.idField)

	g.P("// ", r.name, " returns a handle to the ", r.name, " identified by ", param, ". It performs no calls by itself.")
	if r.parent == nil {
		g.P("func (c *Client) ", r.name, "(", param, " string) ", ref, " {")
		g.P("return ", ref, "{c: c, ", param, ": ", param, "}")
	} else {
		g.P("func (r ", r.parent.name, "Ref) ", r.name, "(", param, " string) ", ref, " {")
		g.P("return ", ref, "{")
		g.P("c: r.c,")
		for _, a := range r.parent.chain {
			g.P(idVar(a.idField), ": r.", idVar(a.idField), ",")
		}
		g.P(param, ": ", param, ",")
		g.P("}")
	}
	g.P("}")
	g.P()

	g.P("// ", ref, " identifies a ", r.name, ".")
	g.P("type ", ref, " struct {")
	g.P("c *Client")
	for _, a := range r.chain {
		g.P(idVar(a.idField), " string")
	}
	g.P("}")
	g.P()
}

func genList(g *protogen.GeneratedFile, q *listQuery) {
	qt := q.name + "Query"
	item := "*" + g.QualifiedGoIdent(q.items.Message.GoIdent)
	page := g.QualifiedGoIdent(fluentPkg.Ident("Page")) + "[" + item + "]"
	ctx := g.QualifiedGoIdent(contextPkg.Ident("Context"))
	rpc := q.service.GoName + "." + q.method.GoName

	// Entry point on the parent.
	g.P("// ", q.name, " starts a query calling ", rpc, ".")
	comment(g, q.method.Comments.Leading)
	if q.parent == nil {
		g.P("func (c *Client) ", q.name, "() ", qt, " {")
		g.P("return ", qt, "{c: c}")
	} else {
		g.P("func (r ", q.parent.name, "Ref) ", q.name, "() ", qt, " {")
		g.P("return ", qt, "{")
		g.P("c: r.c,")
		for _, id := range q.ids {
			g.P(lowerFirst(id.GoName), ": r.", lowerFirst(id.GoName), ",")
		}
		g.P("}")
	}
	g.P("}")
	g.P()

	// Query type.
	g.P("// ", qt, " builds ", rpc, " calls. Setters return a modified copy.")
	g.P("type ", qt, " struct {")
	g.P("c      *Client")
	g.P("paging ", fluentPkg.Ident("Paging"))
	for _, id := range q.ids {
		g.P(lowerFirst(id.GoName), " string")
	}
	for _, s := range q.setters {
		g.P(lowerFirst(s.field.GoName), " ", fieldType(g, s.field))
	}
	g.P("}")
	g.P()

	// Setters.
	for _, s := range q.setters {
		fv := lowerFirst(s.field.GoName)
		g.P("// ", s.name, " sets ", s.field.Desc.Name(), ".")
		comment(g, s.field.Comments.Leading)
		g.P("func (q ", qt, ") ", s.name, "(v ", fieldType(g, s.field), ") ", qt, " {")
		g.P("q.", fv, " = v")
		g.P("return q")
		g.P("}")
		g.P()

		if s.shortcut == "" {
			continue
		}
		for _, v := range s.field.Enum.Values {
			if v.Desc.Number() == 0 {
				continue
			}
			name := shortcutName(s, v)
			g.P("// ", name, " sets ", s.field.Desc.Name(), " to ", v.Desc.Name(), ".")
			comment(g, v.Comments.Leading)
			g.P("func (q ", qt, ") ", name, "() ", qt, " {")
			g.P("q.", fv, " = ", v.GoIdent)
			g.P("return q")
			g.P("}")
			g.P()
		}
	}

	// Paging and terminal operations.
	g.P("// PageSize sets how many items each request fetches. Zero uses the server default.")
	g.P("func (q ", qt, ") PageSize(n int) ", qt, " {")
	g.P("q.paging.PageSize = int32(n)")
	g.P("return q")
	g.P("}")
	g.P()
	g.P("// Limit caps the total number of items returned by All and Collect. Zero means no limit.")
	g.P("func (q ", qt, ") Limit(n int) ", qt, " {")
	g.P("q.paging.Limit = n")
	g.P("return q")
	g.P("}")
	g.P()
	g.P(`// Page fetches one page. Pass "" for the first page and the previous Page.NextPageToken after that.`)
	g.P("func (q ", qt, ") Page(ctx ", ctx, ", pageToken string) (", page, ", error) {")
	g.P("return q.fetch(ctx, q.paging.PageSize, pageToken)")
	g.P("}")
	g.P()
	g.P("// All iterates over every item across pages, fetching each page as it is reached.")
	g.P("func (q ", qt, ") All(ctx ", ctx, ") ", iterPkg.Ident("Seq2"), "[", item, ", error] {")
	g.P("return ", fluentPkg.Ident("All"), "(ctx, q.paging, q.fetch)")
	g.P("}")
	g.P()
	g.P("// Collect returns every item across pages. Set Limit to bound large result sets.")
	g.P("func (q ", qt, ") Collect(ctx ", ctx, ") ([]", item, ", error) {")
	g.P("return ", fluentPkg.Ident("Collect"), "(q.All(ctx))")
	g.P("}")
	g.P()
	g.P("func (q ", qt, ") fetch(ctx ", ctx, ", pageSize int32, pageToken string) (", page, ", error) {")
	g.P("stub := ", q.importPath.Ident("New"+q.service.GoName+"Client"), "(q.c.Conn.ClientConn())")
	g.P("resp, err := stub.", q.method.GoName, "(q.c.Conn.Outgoing(ctx), &", q.method.Input.GoIdent, "{")
	for _, id := range q.ids {
		g.P(id.GoName, ": q.", lowerFirst(id.GoName), ",")
	}
	g.P(q.pageSize.GoName, ": pageSize,")
	g.P(q.pageToken.GoName, ": pageToken,")
	for _, s := range q.setters {
		g.P(s.field.GoName, ": q.", lowerFirst(s.field.GoName), ",")
	}
	g.P("})")
	g.P("if err != nil {")
	g.P("return ", page, "{}, err")
	g.P("}")
	g.P("return ", page, "{Items: resp.Get", q.items.GoName, "(), NextPageToken: resp.Get", q.nextToken.GoName, "()}, nil")
	g.P("}")
	g.P()
}

func fieldType(g *protogen.GeneratedFile, f *protogen.Field) string {
	switch f.Desc.Kind() {
	case protoreflect.BoolKind:
		return "bool"
	case protoreflect.StringKind:
		return "string"
	case protoreflect.BytesKind:
		return "[]byte"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "int32"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "uint32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "int64"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return "uint64"
	case protoreflect.FloatKind:
		return "float32"
	case protoreflect.DoubleKind:
		return "float64"
	case protoreflect.EnumKind:
		return g.QualifiedGoIdent(f.Enum.GoIdent)
	}
	panic("unsupported kind " + f.Desc.Kind().String()) // rejected by checkSetterType
}

// comment emits proto comments as a Go doc paragraph.
func comment(g *protogen.GeneratedFile, c protogen.Comments) {
	text := strings.TrimRight(string(c), "\n")
	if strings.TrimSpace(text) == "" {
		return
	}
	g.P("//")
	for line := range strings.SplitSeq(text, "\n") {
		g.P("//", line)
	}
}

// shortcutName applies the enum_shortcut pattern to an enum value, stripping the
// enum's UPPER_SNAKE prefix: MERGE_FILTER_EXCLUDE with "%sMerges" -> ExcludeMerges.
func shortcutName(s setter, v *protogen.EnumValue) string {
	prefix := upperSnake(string(s.field.Enum.Desc.Name())) + "_"
	return fmt.Sprintf(s.shortcut, camel(strings.TrimPrefix(string(v.Desc.Name()), prefix)))
}

// idVar is the Go variable/field name for an id field: shelf_id -> shelfId.
func idVar(protoField string) string {
	return lowerFirst(camel(protoField))
}

// camel converts snake_case or UPPER_SNAKE to CamelCase.
func camel(s string) string {
	var b strings.Builder
	for part := range strings.SplitSeq(s, "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(strings.ToLower(part[1:]))
	}
	return b.String()
}

// upperSnake converts CamelCase to UPPER_SNAKE: BranchOrder -> BRANCH_ORDER.
func upperSnake(s string) string {
	var b strings.Builder
	runes := []rune(s)
	for i, r := range runes {
		if i > 0 && unicode.IsUpper(r) &&
			(unicode.IsLower(runes[i-1]) || unicode.IsDigit(runes[i-1]) || (i+1 < len(runes) && unicode.IsLower(runes[i+1]))) {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToUpper(r))
	}
	return b.String()
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}
